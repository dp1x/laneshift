"""Build the kev-v2-scene Kev fine-tuning dataset from recordings.

The builder is deliberately separate from the game. It reads the planned
recordings, emits Kev System One scene-prompt rows, keeps human and safe_teacher
provenance separate, and refuses to write a split that leaks a seed.

No teacher action is relabelled. Every included row is the action the teacher
or the human actually took in the recorded state. The prompt is generated by
the same ``OnnxKevPolicy._encode`` path the live controller uses, so the token
count and legal-action set match inference exactly.
"""

