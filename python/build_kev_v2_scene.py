def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--recordings", type=Path, default=DEFAULT_RECORDINGS)
    parser.add_argument("--plan", type=Path, default=DEFAULT_PLAN)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--public-output", type=Path, default=DEFAULT_PUBLIC_OUTPUT)
    parser.add_argument("--tokenizer", type=Path, default=DEFAULT_TOKENIZER)
    parser.add_argument("--prompt-length", type=int, default=256)
    parser.add_argument("--stride", type=int, default=2)
    parser.add_argument("--strict", action="store_true", help="fail on any quality-gate problem")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    if not args.plan.exists():
        raise SystemExit(f"seed plan not found: {args.plan}")
    if not args.tokenizer.exists():
        raise SystemExit(f"tokenizer not found: {args.tokenizer}")
    plan = load_plan(args.plan)
    from tokenizers import Tokenizer
    from policies.onnx_kev import OnnxKevPolicy

    tokenizer = Tokenizer.from_file(str(args.tokenizer))
    policy = OnnxKevPolicy(
        model_path=str(args.tokenizer),
        tokenizer_path=str(args.tokenizer),
        length=args.prompt_length,
        prompt_mode="scene",
    )
    policy.tok = tokenizer
    candidates, extra_counts = extract_candidates(
        args.recordings, plan, policy, args.prompt_length, args.stride
    )
    episode_index = _episode_index(args.recordings, plan)
    validation = validate(candidates, plan, args.prompt_length)
    if validation["problems"]:
        raise SystemExit("dataset validation failed:\n" + "\n".join(validation["problems"]))
    if args.strict and validation["warnings"]:
        raise SystemExit("dataset validation warnings (strict):\n" + "\n".join(validation["warnings"]))
    card = write_dataset(
        candidates,
        episode_index,
        args.plan,
        plan,
        args.output,
        args.public_output,
        args.tokenizer,
        args.prompt_length,
        args.stride,
        extra_counts,
        validation,
    )
    print(json.dumps({
        "output": str(args.output),
        "public_output": str(args.public_output),
        "rows": card["counts"]["included"],
        "splits": {k: v["rows"] for k, v in card["splits"].items()},
        "actions": card["action_counts"],
        "tokens": card["tokens"],
        "warnings": validation["warnings"],
    }, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
